// Generates watch/Shared/Plan.swift from PLAN and ALTS in index.html, so the Watch uses
// exactly the web app's exercise ids, sets, rep ranges, rest strings and alternative ids.
// Usage: node watch/tools/gen-plan.mjs   (run again whenever PLAN or ALTS changes)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const html = readFileSync(join(root, 'index.html'), 'utf8');

const grab = (start, end) => {
  const i = html.indexOf(start), j = html.indexOf(end, i);
  if (i < 0 || j < 0) throw new Error('Could not find ' + start);
  return html.slice(i, j);
};
// Run the web app's own definitions so slug/altId/restSecs behave identically.
const src = [
  grab('const PLAN = {', 'const SESS_KEYS'),
  grab('const slug = ', 'const EXMAP'),
  grab('function restSecs(', 'const mmss'),
  'globalThis.out = {PLAN, ALTS, altId, restSecs};',
].join('\n');
const ctx = {};
vm.runInNewContext(src, ctx);
const { PLAN, ALTS, altId, restSecs } = ctx.out;

const q = s => JSON.stringify(s);
const lines = [];
lines.push('// GENERATED by watch/tools/gen-plan.mjs from PLAN and ALTS in index.html. Do not edit by hand.');
lines.push('');
lines.push('enum Plan {');
lines.push('    /// Weekday (Calendar weekday: 1 = Sunday ... 7 = Saturday) to session key. Saturday is the optional run, logged as run2.');
const week = Object.entries(PLAN.week).map(([d, k]) => [+d + 1, +d === 6 ? 'run2' : k]).sort((a, b) => a[0] - b[0]);
lines.push('    static let week: [Int: String] = [' + week.map(([d, k]) => `${d}: ${q(k)}`).join(', ') + ']');
lines.push('');
lines.push('    static let sessions: [String: PlanSession] = [');
for (const [key, S] of Object.entries(PLAN.sessions)) {
  lines.push(`        ${q(key)}: PlanSession(key: ${q(key)}, name: ${q(S.name)}, type: .${S.type}, note: ${S.note ? q(S.note) : 'nil'}, exercises: [`);
  for (const e of S.ex || []) {
    const alts = (ALTS[e.id] || []).map(n => `PlanAlt(id: ${q(altId(e.id, n))}, name: ${q(n)})`);
    lines.push(`            PlanExercise(id: ${q(e.id)}, name: ${q(e.name)}, sets: ${e.sets}, reps: ${e.reps[0]}...${e.reps[1]}, rest: ${q(e.rest)}, restSeconds: ${restSecs(e.rest)}, note: ${e.note ? q(e.note) : 'nil'}, small: ${!!e.small}, superset: ${e.superset ? q(e.superset) : 'nil'}, alts: [`);
    alts.forEach((a, i) => lines.push(`                ${a}${i < alts.length - 1 ? ',' : ''}`));
    lines.push('            ]),');
  }
  lines.push('        ]),');
}
lines.push('    ]');
lines.push('}');
lines.push('');

const out = join(root, 'watch', 'Shared', 'Plan.swift');
writeFileSync(out, lines.join('\n'));
console.log('Wrote', out);
